/**
 * OpenCode websearch provider plugin generation.
 *
 * The Console writes `websearch.provider = "<provider>"` into the user's
 * opencode.jsonc. That value resolves to a WebSearch provider the local plugin
 * below registers with OpenCode. The plugin reads the gateway URL and API key
 * from the matching provider entry in opencode.jsonc — the same provider block
 * the injector writes — so the search route follows the configured provider.
 *
 * OpenCode loads every `.js` file under `~/.config/opencode/plugins/`
 * (or `<config-dir>/plugins/`) as a plugin; no registration step is needed
 * beyond writing the file.
 */
import { ensureDir, fileExists, join, removeFile, writeTextFileWithBackup } from "./fs-ops";

const PLUGIN_FILENAME = (providerName: string) => `${providerName}-websearch.js`;

/** Escapes the provider name for use inside a JS double-quoted string. */
function jsStringLiteral(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
}

/**
 * Renders the websearch plugin source for one provider name.
 *
 * `providerName` is the exact provider key written into opencode.jsonc (e.g.
 * `Cartethyia`, `CarteLocal`). The plugin reads that block's `baseURL` and
 * `apiKey` as the single source of truth, so no secret is duplicated anywhere.
 */
export function renderWebsearchPlugin(providerName: string): string {
  const quoted = jsStringLiteral(providerName);
  return `// ${quoted}-websearch — route OpenCode's built-in websearch tool through the
// Cartethyia gateway's /v1/search native route, using the "${quoted}"
// provider block in opencode.jsonc as the single source of truth.
//
// Generated by the Cartethyia console (CLI tools → OpenCode). Do not edit by
// hand; re-apply the tool config to regenerate.
//
// Env overrides (all optional):
//   CARTETHYIA_SEARCH_URL      (default: the provider's baseURL + /search)
//   CARTETHYIA_SEARCH_API_KEY  (default: the provider's apiKey)
//   CARTETHYIA_SEARCH_BACKEND  (default: "exa"; "parallel" also works)

import { Plugin } from "@opencode/plugin";
import { readFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

function pick(obj, keys) {
  for (const k of keys) {
    const v = obj?.[k];
    if (v !== undefined && v !== null) return v;
  }
  return undefined;
}

// Pull the "${quoted}" provider's baseURL/apiKey out of opencode.jsonc.
// The file is JSONC (comments allowed) so search for the provider block
// loosely rather than parsing strictly.
function readProviderSettings() {
  const candidates = [
    process.env.OPENCODE_CONFIG,
    join(homedir(), ".config", "opencode", "opencode.jsonc"),
    join(homedir(), ".config", "opencode", "opencode.json"),
  ];
  for (const path of candidates) {
    if (!path) continue;
    let text;
    try {
      text = readFileSync(path, "utf8");
    } catch {
      continue;
    }
    // Find the provider block, then the next provider block or closing brace.
    const providerStart = text.indexOf(\`"\${PROVIDER_NAME}"\`);
    if (providerStart < 0) continue;
    const settingsMatch = text.slice(providerStart).match(/"settings"\\s*:\\s*\\{/);
    if (!settingsMatch) continue;
    const settingsStart = providerStart + settingsMatch.index + settingsMatch[0].length - 1;
    let depth = 0;
    let end = -1;
    for (let i = settingsStart; i < text.length; i++) {
      const ch = text[i];
      if (ch === "{") depth += 1;
      else if (ch === "}") {
        depth -= 1;
        if (depth === 0) {
          end = i;
          break;
        }
      }
    }
    if (end < 0) continue;
    const settings = text.slice(settingsStart, end + 1);
    const baseURL = settings.match(/"baseURL"\\s*:\\s*"([^"]+)"/)?.[1];
    const apiKey = settings.match(/"apiKey"\\s*:\\s*"([^"]+)"/)?.[1];
    if (baseURL) {
      return { baseURL, apiKey };
    }
  }
  return { baseURL: undefined, apiKey: undefined };
}

const PROVIDER_NAME = "${quoted}";
const local = readProviderSettings();
const BASE_URL = (process.env.CARTETHYIA_SEARCH_URL || (local.baseURL ? \`\${local.baseURL.replace(/\\/+$/, "")}/search\` : "")).replace(/\\/+$/, "");
const API_KEY = process.env.CARTETHYIA_SEARCH_API_KEY || local.apiKey || "";
const BACKEND = process.env.CARTETHYIA_SEARCH_BACKEND || "exa";

export default Plugin.define({
  id: "${quoted}-websearch",
  async setup(ctx) {
    await ctx.websearch.transform((editor) => {
      editor.add({
        id: "${quoted}",
        name: "Cartethyia Search",
        execute: async ({ query }, { signal }) => {
          if (!BASE_URL) {
            throw new Error(
              "Cartethyia search gateway is not configured: set CARTETHYIA_SEARCH_URL or add a ${quoted} provider with baseURL in opencode.jsonc",
            );
          }
          const response = await fetch(BASE_URL, {
            method: "POST",
            headers: {
              "content-type": "application/json",
              ...(API_KEY ? { authorization: \`Bearer \${API_KEY}\` } : {}),
            },
            body: JSON.stringify({
              model: BACKEND,
              query,
              max_results: 8,
            }),
            signal,
          });
          if (!response.ok) {
            const text = await response.text().catch(() => "");
            throw new Error(
              \`Cartethyia search failed (HTTP \${response.status}): \${text.slice(0, 200)}\`,
            );
          }
          const data = await response.json();
          const results = Array.isArray(data?.results) ? data.results : [];
          return results.map((item) => ({
            url: String(item?.url ?? ""),
            title: typeof item?.title === "string" && item.title ? item.title : undefined,
            content: typeof item?.snippet === "string" && item.snippet ? item.snippet : undefined,
            time:
              typeof item?.published_at === "string" && item.published_at
                ? { published: Date.parse(item.published_at) || undefined }
                : {},
          }));
        },
      });
      editor.default.set("${quoted}");
    });
  },
});
`;
}

/** Writes the websearch plugin for a provider into the OpenCode config dir. */
export async function writeWebsearchPlugin(
  configDir: string,
  providerName: string,
): Promise<string> {
  const pluginsDir = join(configDir, "plugins");
  await ensureDir(pluginsDir);
  const filename = PLUGIN_FILENAME(providerName);
  const target = join(pluginsDir, filename);
  await writeTextFileWithBackup(target, renderWebsearchPlugin(providerName));
  return target;
}

/** Removes the websearch plugin for a provider from the OpenCode config dir. */
export async function removeWebsearchPlugin(
  configDir: string,
  providerName: string,
): Promise<boolean> {
  const target = join(configDir, "plugins", PLUGIN_FILENAME(providerName));
  if (await fileExists(target)) {
    await removeFile(target);
    return true;
  }
  return false;
}
